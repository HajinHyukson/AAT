# Build CSV rows
def build_row(key, name, unit, vt, dirn, family, desc, ovr):
    f = FAM[family]
    base = {
        "key": key,
        "display_name": name,
        "description": desc,
        "family": ovr.get("family", family),
        "unit": unit,
        "value_type": vt,
        "directionality": dirn,
        **{k: f.get(k, "") for k in [
            "source_type", "connector_roles", "frequency", "coverage", "freshness",
            "timestamp_policy", "observed_at_policy", "available_at_policy", "retrieved_at_policy",
            "source_version_policy", "data_version_policy", "model_version_policy",
            "vintage_required", "lookahead_risk",
            "entitlement_policy", "cache_policy", "display_policy", "export_policy",
            "derived_value_policy", "redistribution_policy", "marketplace_policy",
            "production_scoring_eligible", "evidence_only", "research_only",
            "compatible_node_types", "compatible_strategy_profiles", "limitations",
            "validation_requirements", "failure_modes",
            "confidence_label", "source_sections", "source_ids",
        ]},
    }
    base.update(ovr)
    # Apply restrictive defaults for ambiguous license_policy
    lp = base["entitlement_policy"]
    if lp in ("unknown", "restricted_or_unclear"):
        if base["export_policy"] not in ("blocked", "conditional"):
            base["export_policy"] = "blocked"
        if base["marketplace_policy"] not in ("redacted", "blocked"):
            base["marketplace_policy"] = "redacted"
        if base["redistribution_policy"] not in ("blocked", "conditional"):
            base["redistribution_policy"] = "blocked"
    if lp == "licensed_provider_required":
        if base["redistribution_policy"] not in ("blocked", "conditional"):
            base["redistribution_policy"] = "blocked"
        if base["marketplace_policy"] not in ("redacted", "blocked", "conditional"):
            base["marketplace_policy"] = "redacted"
    if lp == "internal_research_only":
        base["export_policy"] = "blocked"
        base["redistribution_policy"] = "blocked"
        base["marketplace_policy"] = "blocked"
    # Reproject confidence: missing source_ids -> downgrade
    if not base.get("source_ids") or len(base["source_ids"]) == 0:
        if base["confidence_label"] in ("high_confidence_core", "common_practice"):
            base["confidence_label"] = "research_supported_experimental"
    return [base.get(c, "") for c in ATTR_COLUMNS]


